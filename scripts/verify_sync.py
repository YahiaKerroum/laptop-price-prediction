#!/usr/bin/env python3
"""Verify the organized repo carries the same content as `DataminingProject (1)`.

The reorganisation claim is "same project, organized". This script checks it
rather than asserting it: every file in the source folder is matched to its new
location and compared by content hash (after normalising CRLF line endings,
which is the only difference the move itself introduced).

Deliberate, documented differences are declared in EXPECTED_DIFFERENCES so the
report distinguishes "changed on purpose" from "lost in the move".

Usage::

    python3 scripts/verify_sync.py [path/to/DataminingProject (1)]

Exit code is 0 when nothing is unexplained.
"""

